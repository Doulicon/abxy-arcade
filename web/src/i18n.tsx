type TextMap = Record<string, string>;

type I18nCtx = {
  locale: LocaleId;
  setLocale: (id: LocaleId) => void;
  locales: LocaleMeta[];
  /** 系统级文字 */
  t: (key: string, vars?: Record<string, string | number>) => string;
  /** 站点展示文案（后台可编辑） */
  tx: (key: string) => string;
  texts: TextMap;
  reloadTexts: () => Promise<void>;
};

const Ctx = createContext<I18nCtx>({
  locale: DEFAULT_LOCALE,
  setLocale: () => undefined,
  locales: LOCALES,
  t: (key) => key,
  tx: (key) => '',
  texts: {},
  reloadTexts: async () => undefined,
});

function detectLocale(): LocaleId {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as LocaleId | null;
    if (saved && LOCALE_IDS.includes(saved)) return saved;
  } catch {
    /* 隐私模式忽略 */
  }
  const nav = (navigator.languages?.[0] || navigator.language || 'zh').toLowerCase();
  if (nav.startsWith('zh')) {
    return /hant|tw|hk|mo/.test(nav) ? 'zh-Hant' : 'zh';
  }
  if (nav.startsWith('ja')) return 'ja';
  if (nav.startsWith('ko')) return 'ko';
  if (nav.startsWith('ru')) return 'ru';
  if (nav.startsWith('en')) return 'en';
  return DEFAULT_LOCALE;
}

function interpolate(tpl: string, vars?: Record<string, string | number>) {
  if (!vars) return tpl;
  return tpl.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<LocaleId>(detectLocale);
  const [texts, setTexts] = useState<TextMap>({});

  const reloadTexts = useCallback(async () => {
    try {
      const res = await api.get<{ texts: TextMap }>(`/texts?locale=${encodeURIComponent(locale)}`);
      setTexts(res.texts || {});
    } catch {
      setTexts({});
    }
  }, [locale]);

  useEffect(() => {
    reloadTexts();
  }, [reloadTexts]);

  useEffect(() => {
    const meta = LOCALES.find((l) => l.id === locale) || LOCALES[0];
    document.documentElement.lang = meta.htmlLang;
    document.documentElement.dataset.locale = locale;
  }, [locale]);

  const setLocale = useCallback((id: LocaleId) => {
    if (!LOCALE_IDS.includes(id)) return;
    setLocaleState(id);
    try {
      localStorage.setItem(STORAGE_KEY, id);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const raw =
        SYS[locale]?.[key] ??
        SYS_EXTRA[locale]?.[key] ??
        SYS_ADMIN[locale]?.[key] ??
        SYS[DEFAULT_LOCALE][key] ??
        SYS_EXTRA[DEFAULT_LOCALE][key] ??
        SYS_ADMIN[DEFAULT_LOCALE][key] ??
        key;
      return interpolate(raw, vars);
    },
    [locale],
  );

  const tx = useCallback((key: string) => texts[key] ?? '', [texts]);

  const value = useMemo(
    () => ({ locale, setLocale, locales: LOCALES, t, tx, texts, reloadTexts }),
    [locale, setLocale, t, tx, texts, reloadTexts],
  );

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}

/** 文案里的 {year} 由前端补上当前年份 */
export function useCopyright(raw: string) {
  return useMemo(() => raw.replace(/\{year\}/g, String(new Date().getFullYear())), [raw]);
}

